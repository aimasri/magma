#!/usr/bin/env php
<?php

// Build script to pre-compile and cache routes
/**
 * Title: Route Caching Script
 *
 * Purpose:
 * - Pre-compile dynamic routing regular expressions and serialize them into a flat PHP array.
 *
 * Why / Why this design:
 * - Compiling regex patterns on every HTTP request is computationally expensive. By moving this 
 *   to a build step, the production Router can simply use static `require` and $O(1)$ array lookups, 
 *   leveraging PHP's OPcache for maximum speed.
 *
 * Teaching notes:
 * - This file represents the "Build Phase" of the application. In a real CI/CD pipeline, this 
 *   script runs during deployment so the production server never wastes CPU cycles compiling routes.
 */

// Load application bootstrap to initialize the autoloader and basic environment
require_once dirname(__DIR__) . '/core/config/bootstrap.php';

use Magma\routing\Router;

$routesFile = ROOT_DIR . '/core/config/routes.php';
$cacheFile = ROOT_DIR . '/core/config/routes.cache.php';

if (!file_exists($routesFile)) {
    echo "Routes file not found at {$routesFile}\n";
    exit(1);
}

$routes = require $routesFile;
$cachedRoutes = [];

echo "Compiling routes...\n";

foreach ($routes as $route) {
    $path = $route[1];
    $constraints = $route[3] ?? [];
    
    // Compile regex
    $pattern = Router::compilePattern($path, $constraints);
    
    // Append the compiled regex as the 7th element (index 6)
    $route[6] = $pattern;
    
    $cachedRoutes[] = $route;
    
    echo "Compiled: {$route[0]} {$path} -> {$pattern}\n";
}

$exported = var_export($cachedRoutes, true);

// Add standard PHP opening tag and return statement
$fileContent = "<?php\n\n// THIS FILE IS AUTO-GENERATED BY bin/cache_routes.php\n// DO NOT EDIT MANUALLY\n\nreturn " . $exported . ";\n";

if (file_put_contents($cacheFile, $fileContent)) {
    echo "\nRoutes successfully cached to: {$cacheFile}\n";
    exit(0);
} else {
    echo "\nFailed to write cache file: {$cacheFile}\n";
    exit(1);
}
