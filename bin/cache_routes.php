#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Title: Route Manifest Pre-Compilation CLI Tool
 *
 * Purpose:
 * - Pre-compiles all registered application routes into immutable `Route` Value Objects and mega-regexes.
 * - Exports a static, OPcache-friendly PHP manifest file (`magma/config/routes.cache.php`) via `var_export`.
 *
 * Why / Why this design:
 * - Build-Phase Performance Optimization: Compiling regular expressions and parsing route configuration arrays at HTTP runtime wastes precious CPU cycles. By baking the routes into an OPcache-cached PHP manifest during deployment/build steps, the application achieves instantaneous O(1) routing execution on production environments.
 * - Zero Dependency / Pure PHP: Uses native `var_export` and `Route::__set_state` without requiring external serialization libraries.
 *
 * Teaching notes:
 * - In production CI/CD workflows, execute `php bin/cache_routes.php` as part of the container image build or artifact packaging step.
 */

// 1. Initialize framework bootstrap
require_once dirname(__DIR__) . '/magma/config/bootstrap.php';

use Magma\routing\Route;
use Magma\routing\RouteCollection;
use Magma\routing\RouteCompiler;

echo "====================================================\n";
echo " Magma Framework: Route Manifest Pre-Compiler\n";
echo "====================================================\n\n";

$cacheFile = ROOT_DIR . '/magma/config/routes.cache.php';

echo "Discovering route definitions dynamically...\n";

/** @var array $rawRoutes */
$rawRoutes = \Magma\routing\RouteDiscoveryEngine::discoverRoutes();

if (!is_array($rawRoutes)) {
    fwrite(STDERR, "Error: Routes discovery engine must return an array.\n");
    exit(1);
}

$collection = new RouteCollection($rawRoutes);
$allRoutes = $collection->all();
$dynamicRoutes = $collection->getDynamicRoutes();

echo sprintf("Found %d total registered routes (%d dynamic).\n\n", count($allRoutes), count($dynamicRoutes, COUNT_RECURSIVE) - count($dynamicRoutes));

$compiledRoutes = [];

foreach ($allRoutes as $index => $route) {
    if (!$route instanceof Route) {
        $route = Route::fromTuple((array)$route);
    }

    if ($route->hasParameters()) {
        $compiledPattern = RouteCompiler::compilePattern($route->getUri(), $route->getConstraints());
        $route = $route->withCompiledRegex($compiledPattern);
        echo sprintf("  [DYNAMIC] %-7s %-30s -> %s\n", $route->getMethod(), $route->getUri(), $compiledPattern);
    } else {
        echo sprintf("  [STATIC]  %-7s %-30s\n", $route->getMethod(), $route->getUri());
    }

    $compiledRoutes[] = $route;
}

$exportedData = var_export($compiledRoutes, true);

$manifestContent = <<<PHP
<?php

declare(strict_types=1);

/**
 * THIS FILE IS AUTOMATICALLY GENERATED BY bin/cache_routes.php.
 * DO NOT EDIT THIS MANIFEST DIRECTLY.
 *
 * Generated at: %s
 */

use Magma\\routing\\Route;

return %s;

PHP;

$finalContent = sprintf($manifestContent, date('c'), $exportedData);

if (file_put_contents($cacheFile, $finalContent, LOCK_EX) === false) {
    fwrite(STDERR, "\nError: Failed to write route cache manifest to [{$cacheFile}].\n");
    exit(1);
}

echo "\n====================================================\n";
echo " Route manifest successfully compiled and cached to:\n";
echo " {$cacheFile}\n";
echo "====================================================\n";
exit(0);
